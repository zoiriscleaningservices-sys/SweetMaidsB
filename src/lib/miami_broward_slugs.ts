// Helper to determine if a slug belongs to Monroe County (Florida Keys)
export function isMonroeCounty(slug: string, clean_name: string = ''): boolean {
  if (!slug && !clean_name) return false;
  const s = (slug || '').toLowerCase().trim();
  const c = (clean_name || '').toLowerCase().trim();

  // Exclude false friends from other Florida counties
  if (
    s.includes("keystone") ||
    s.includes("longboat-key") ||
    s.includes("siesta-key") ||
    s.includes("lido-key") ||
    s.includes("bird-key") ||
    s.includes("manasota-key") ||
    s.includes("key-vista") ||
    s.includes("whiskey-creek")
  ) {
    return false;
  }
  if (
    c.includes("keystone") ||
    c.includes("longboat key") ||
    c.includes("siesta key") ||
    c.includes("lido key") ||
    c.includes("bird key") ||
    c.includes("manasota key") ||
    c.includes("key vista") ||
    c.includes("whiskey creek")
  ) {
    return false;
  }

  // Check known slug list
  if (monroeCountySlugs.includes(s)) return true;

  // Check county or general Florida Keys indicators
  if (s.includes("monroe") || c.includes("monroe")) return true;
  if (
    s.includes("florida-keys") ||
    c.includes("florida keys") ||
    s === "the-keys" ||
    s === "the-keys-fl" ||
    s === "keys-fl" ||
    s === "keys"
  ) {
    return true;
  }

  // Check city name matches
  for (const city of monroeCityNames) {
    if (c === city || c.startsWith(city + ' ') || c.endsWith(' ' + city) || c.includes(city)) {
      return true;
    }
  }

  // Prefix checks for slug
  if (
    s.startsWith("key-west") ||
    s.startsWith("key-largo") ||
    s.startsWith("marathon") ||
    s.startsWith("islamorada") ||
    s.startsWith("tavernier") ||
    s.startsWith("big-pine") ||
    s.startsWith("big-coppitt") ||
    s.startsWith("duck-key") ||
    s.startsWith("cudjoe") ||
    s.startsWith("stock-island") ||
    s.startsWith("key-colony") ||
    s.startsWith("summerland") ||
    s.startsWith("sugarloaf") ||
    s.startsWith("ramrod") ||
    s.startsWith("little-torch") ||
    s.startsWith("big-torch") ||
    s.startsWith("middle-torch") ||
    s.startsWith("plantation-key") ||
    s.startsWith("matecumbe") ||
    s.startsWith("grassy-key") ||
    s.startsWith("conch-key") ||
    s.startsWith("boca-chica") ||
    s.startsWith("bay-point") ||
    s.startsWith("flamingo") ||
    s.startsWith("layton") ||
    s.startsWith("long-key") ||
    s.startsWith("fiesta-key") ||
    s.startsWith("pigeon-key") ||
    s.startsWith("bahia-honda") ||
    s.startsWith("no-name-key") ||
    s.startsWith("saddlebunch") ||
    s.startsWith("shark-key") ||
    s.startsWith("geiger-key")
  ) {
    return true;
  }

  return false;
}

// Check if slug belongs to the (305) / (786) telephone routing zone (Miami-Dade, Broward, Monroe County / Florida Keys)
export function is305Area(slug: string, clean_name: string = ''): boolean {
  if (!slug && !clean_name) return false;
  const s = (slug || '').toLowerCase().trim();
  const c = (clean_name || '').toLowerCase().trim();
  return miamiBrowardSlugs.includes(s) || isMonroeCounty(s, c);
}
